package net.bumblebee.claysoldiers.dev;

import com.mojang.brigadier.arguments.ArgumentType;
import com.mojang.brigadier.context.CommandContext;
import com.mojang.brigadier.exceptions.CommandSyntaxException;
import com.mojang.brigadier.suggestion.SuggestionProvider;
import net.minecraft.commands.CommandSourceStack;
import net.minecraft.core.RegistryAccess;
import net.minecraft.network.chat.Component;
import org.jetbrains.annotations.Nullable;

import java.util.List;
import java.util.function.Function;

/**
 * One dev command and its book button(s), defined once in the {@link DevToolRegistry}.
 *
 * @param id          unique id
 * @param category    id of a {@link DevCategory} in the same registry
 * @param label       button text in the book
 * @param description one line, shown when hovering the button and in confirm prompts
 * @param root        the command root: {@link #ROOT_COMMAND} for generated tools, anything else for links
 * @param path        words after the root, e.g. {@code ["scenario", "build_test"]}
 * @param confirm     whether running it first asks for a second click
 * @param argument    optional single argument; the book gets one button per {@link Argument#choices choice}
 * @param action      what the command does; {@code null} for a {@link #link link}
 */
public record DevTool(String id, String category, Component label, String description, String root, List<String> path,
                      boolean confirm, @Nullable Argument argument, @Nullable Action action) {
    public static final String ROOT_COMMAND = "/csr dev";

    public DevTool {
        path = List.copyOf(path);
        if (path.isEmpty()) {
            throw new IllegalArgumentException("Dev tool " + id + " needs a command path");
        }
        if (action == null && confirm) {
            throw new IllegalArgumentException("Link " + id + " cannot ask for confirmation");
        }
    }

    /**
     * A tool whose {@code /csr dev <path>} command is generated by the {@link DevToolRegistry}.
     */
    public DevTool(String id, String category, Component label, String description, List<String> path,
                   boolean confirm, @Nullable Argument argument, Action action) {
        this(id, category, label, description, ROOT_COMMAND, path, confirm, argument, action);
    }

    /**
     * A book entry for a command that is registered elsewhere (not under {@code /csr dev}), e.g. {@code /csr build}.
     * The coverage GameTests check that its buttons are real commands.
     *
     * @param command  the command without its argument, e.g. {@code /csr build}
     * @param argument choices for the book buttons; its type is not used
     */
    public static DevTool link(String id, String category, Component label, String description, String command, @Nullable Argument argument) {
        List<String> words = List.of(command.trim().split(" +"));
        if (words.size() < 2 || !words.getFirst().startsWith("/")) {
            throw new IllegalArgumentException("Link " + id + " needs a command like /csr build, got " + command);
        }
        return new DevTool(id, category, label, description, words.getFirst(), words.subList(1, words.size()), false, argument, null);
    }

    /**
     * Whether this is a book entry for a command registered elsewhere.
     */
    public boolean isLink() {
        return action == null;
    }

    /**
     * The command this tool runs, without its argument, e.g. {@code /csr dev materials}.
     */
    public String command() {
        return root + " " + String.join(" ", path);
    }

    /**
     * The command usage, e.g. {@code /csr dev materials <blueprint>}.
     */
    public String usage() {
        return argument == null ? command() : command() + " <" + argument.name() + ">";
    }

    /**
     * What the command does when run.
     */
    @FunctionalInterface
    public interface Action {
        int run(CommandContext<CommandSourceStack> context) throws CommandSyntaxException;
    }

    /**
     * A command argument and the values the book offers as buttons.
     *
     * @param name        argument name, used with e.g. {@code ResourceLocationArgument.getId(context, name)}
     * @param type        brigadier argument type
     * @param suggestions tab-completion suggestions, or {@code null}
     * @param choices     values to offer in the book; read from registries where possible so new content appears automatically
     */
    public record Argument(String name, ArgumentType<?> type, @Nullable SuggestionProvider<CommandSourceStack> suggestions,
                           Function<RegistryAccess, List<Choice>> choices) {
    }

    /**
     * One book button for an argument value.
     *
     * @param label button text
     * @param value text appended to the command
     */
    public record Choice(Component label, String value) {
    }
}
